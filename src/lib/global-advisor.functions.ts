export const generateGlobalAdvisorReport = createServerFn({ method: "POST" })
  .middleware([requireSupabaseAuth])
  .handler(async ({ context }) => {
    const apiKey = process.env.LOVABLE_API_KEY;
    if (!apiKey) throw new Error("LOVABLE_API_KEY غير مُهيّأ");

    const { enforceRateLimit } = await import("./security.server");
    await enforceRateLimit({ bucket: "global-advisor", limit: 5, windowSeconds: 3600 });

    const { supabaseAdmin } = await import("@/integrations/supabase/client.server");

    const { data: rows, error } = await supabaseAdmin
      .from("assessment_reports")
      .select("code, name, stage, report, created_at")
      .eq("user_id", context.userId)
      .order("created_at", { ascending: true });

    if (error) throw new Error("تعذّر قراءة تقاريرك.");
    if (!rows || rows.length === 0) {
      throw new Error("لا توجد تقارير في حسابك. أكمل اختباراً واحداً على الأقل أولاً.");
    }

    const userName = rows.find((r) => r.name)?.name || "المستخدم";

    const reportsBlock = rows
      .map(
        (r, i) =>
          `\n\n===== تقرير #${i + 1} — ${r.stage ?? "اختبار"} (كود: ${r.code}) — ${new Date(r.created_at).toLocaleDateString("ar-EG")} =====\n${(r.report ?? "").slice(0, 5000)}`,
      )
      .join("\n");

    const aiRes = await fetch("https://ai.gateway.lovable.dev/v1/chat/completions", {
      method: "POST",
      headers: { Authorization: `Bearer ${apiKey}`, "Content-Type": "application/json" },
      body: JSON.stringify({
        model: "google/gemini-2.5-flash",
        max_tokens: 12000,
        messages: [
          { role: "system", content: SYSTEM_PROMPT + "\n\n" + AI_GUARDRAILS },
          {
            role: "user",
            content: `الاسم: ${userName}\nعدد التقارير المتاحة: ${rows.length}\n\nالتقارير الفعلية للمستخدم:\n${reportsBlock}\n\nاعتمد على هذه البيانات فقط، ولا تخترع نتائج لاختبارات غير مذكورة. أصدر التقرير الشامل وفق الهيكل المحدّد كاملاً.`,
          },
        ],
      }),
    });

    if (!aiRes.ok) {
      if (aiRes.status === 429) throw new Error("تجاوزت الحد المسموح من الطلبات، حاول لاحقاً.");
      if (aiRes.status === 402) throw new Error("نفد رصيد الذكاء الاصطناعي في المنصة.");
      const t = await aiRes.text();
      console.error("global-advisor AI error", aiRes.status, t);
      throw new Error("تعذر توليد التقرير الشامل.");
    }

    const aiJson = await aiRes.json();
    const report: string = aiJson?.choices?.[0]?.message?.content ?? "";
    if (!report) throw new Error("لم يكتمل توليد التقرير. حاول مرة أخرى.");

    return {
      report,
      sources: rows.map((r) => ({ code: r.code, stage: r.stage })),
      generatedAt: new Date().toISOString(),
    };
  });
