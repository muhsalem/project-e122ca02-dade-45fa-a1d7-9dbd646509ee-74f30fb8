export const runSpecializationCompass = createServerFn({ method: "POST" })
  .inputValidator((data: unknown) => Schema.parse(data))
  .handler(async ({ data }) => {
    const { enforceRateLimit } = await import("./security.server");
    await enforceRateLimit({ bucket: "specialization-compass", limit: 20, windowSeconds: 600 });

    const apiKey = process.env.LOVABLE_API_KEY;
    if (!apiKey) throw new Error("LOVABLE_API_KEY غير مُهيّأ");

    const { supabaseAdmin } = await import("@/integrations/supabase/client.server");
    const normalized = data.query.trim().replace(/\s+/g, " ");
    const cacheKey = `compass-v1:${data.mode}:${normalized}`;

    const { data: cached } = await supabaseAdmin
      .from("report_cache")
      .select("report")
      .eq("cache_key", cacheKey)
      .eq("report_type", "specialization_compass")
      .gt("expires_at", new Date().toISOString())
      .maybeSingle();

    if (cached?.report) return { report: cached.report as string, cached: true };

    const systemPrompt = `${BASE_SYSTEM}\n\n${MODE_INSTRUCTIONS[data.mode]}\n\nالتزم بالهيكل والعناوين حرفيًا. لا مقدمات ولا خواتيم خارجه.`;
    const userPrompt = `${MODE_LABEL[data.mode]}: ${normalized}`;

    const aiRes = await fetch("https://ai.gateway.lovable.dev/v1/chat/completions", {
      method: "POST",
      headers: { Authorization: `Bearer ${apiKey}`, "Content-Type": "application/json" },
      body: JSON.stringify({
        model: "google/gemini-2.5-flash",
        max_tokens: 16000,
        messages: [
          { role: "system", content: systemPrompt + AI_GUARDRAILS },
          { role: "user", content: userPrompt },
        ],
      }),
    });

    if (!aiRes.ok) {
      if (aiRes.status === 429) throw new Error("تم تجاوز الحد المسموح. حاول لاحقًا.");
      if (aiRes.status === 402) throw new Error("نفد رصيد الذكاء الاصطناعي.");
      const t = await aiRes.text();
      console.error("AI gateway error:", aiRes.status, t);
      throw new Error("تعذر إنشاء التقرير. حاول مرة أخرى.");
    }

    const aiJson = await aiRes.json();
    const report: string = aiJson?.choices?.[0]?.message?.content ?? "";
    if (!report) throw new Error("لم يكتمل توليد التقرير.");

    await supabaseAdmin.from("report_cache").insert({
      cache_key: cacheKey,
      report_type: "specialization_compass",
      report,
    });

    return { report, cached: false };
  });
